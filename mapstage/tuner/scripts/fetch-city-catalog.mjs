/**
 * Fetch the prefecture-level city catalog from OSM (Overpass):
 *   rel["boundary"="administrative"]["admin_level"="5"] in China area 270056.
 *   (China mapping: 4=省级, 5=地级市/自治州, 6=县级 — verified on Gansu: 14 prefectures.)
 * Writes scripts/city-catalog.mjs (CITY_RAW entries; relId + label).
 *
 * parentId assignment happens later in build-region-isolate.mjs
 * (city centroid inside a province polygon). Zhangye is curated in
 * province-catalog.mjs and de-duplicated by relId there.
 *
 * Usage (from tuner/): node scripts/fetch-city-catalog.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OVERPASS_ENDPOINTS = [
  'https://overpass-api.de/api/interpreter',
  'https://overpass.kumi.systems/api/interpreter',
  'https://overpass.private.coffee/api/interpreter',
];

const QUERY = `[out:json][timeout:180];
area(3600270056)->.cn;
rel(area.cn)["boundary"="administrative"]["admin_level"="5"]["name"];
out ids tags;`;

const root = dirname(fileURLToPath(import.meta.url));
const outPath = join(root, 'city-catalog.mjs');

async function fetchCatalog() {
  let lastErr = null;
  for (const url of OVERPASS_ENDPOINTS) {
    try {
      console.log('Trying ' + url);
      const res = await fetch(url, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/x-www-form-urlencoded',
          'User-Agent': 'mapstage/region-isolate',
        },
        body: 'data=' + encodeURIComponent(QUERY),
      });
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const json = await res.json();
      if (!json || !Array.isArray(json.elements)) throw new Error('no elements');
      return json.elements;
    } catch (err) {
      lastErr = err;
      console.warn('Failed: ' + (err && err.message));
    }
  }
  throw lastErr || new Error('all Overpass endpoints failed');
}

const PROVINCE_LABELS = new Set([
  '北京', '天津', '河北', '山西', '内蒙古', '辽宁', '吉林', '黑龙江', '上海',
  '江苏', '浙江', '安徽', '福建', '江西', '山东', '河南', '湖北', '湖南',
  '广东', '广西', '海南', '重庆', '四川', '贵州', '云南', '西藏', '陕西',
  '甘肃', '青海', '宁夏', '新疆', '香港', '澳门', '台湾',
]);

/** 兰州市→兰州;与省名冲突的(吉林市/海南市)保留全名 */
function cityLabel(tags) {
  const raw = (tags && (tags['name:zh'] || tags.name)) || '';
  if (!raw) return '';
  if (/市$/.test(raw)) {
    const short = raw.slice(0, -1);
    if (short.length >= 2 && !PROVINCE_LABELS.has(short)) return short;
  }
  return raw;
}

const elements = await fetchCatalog();
const cities = [];
const seen = new Set();
for (const el of elements) {
  if (!el || el.type !== 'relation' || !el.id || !el.tags) continue;
  const label = cityLabel(el.tags);
  if (!label) continue;
  const relId = el.id;
  if (seen.has(relId)) continue;
  seen.add(relId);
  cities.push({ relId, label, name: el.tags.name || label });
}
cities.sort((a, b) => a.label.localeCompare(b.label, 'zh'));

if (cities.length < 280) {
  throw new Error('suspiciously few cities: ' + cities.length + ' (expect ~333)');
}

const body =
  '/**\n' +
  ' * Auto-generated by tuner/scripts/fetch-city-catalog.mjs — do not hand-edit.\n' +
  ' * Prefecture-level divisions (admin_level=6) from OpenStreetMap via Overpass.\n' +
  ' * ODbL 1.0 © OpenStreetMap contributors. Narrative silhouettes, not official boundaries.\n' +
  ' * parentId is assigned at build time (centroid inside a province polygon).\n' +
  ' */\n' +
  'export const CITY_CATALOG_FETCHED_AT = ' + JSON.stringify(new Date().toISOString()) + ';\n' +
  'export const CITY_RAW = ' +
  JSON.stringify(
    cities.map((c) => ({ relId: c.relId, label: c.label, name: c.name })),
    null,
    0
  ) +
  ';\n';

writeFileSync(outPath, body, 'utf8');
console.log(
  'Wrote ' + outPath + ' cities=' + cities.length + ' bytes=' + Buffer.byteLength(body)
);
